import pandas as pd
import numpy as np
from sklearn.preprocessing import StandardScaler, OneHotEncoder
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import Pipeline
from sklearn.impute import SimpleImputer
import joblib

"""1. Load Dataset -"""

def load_data(path: str) -> pd.DataFrame:
    """
    Load dataset from CSV file.
    """
    df = pd.read_csv(path)
    return df

"""2. Basic Cleaning -"""

def clean_data(df: pd.DataFrame) -> pd.DataFrame:
    """
    Handle duplicates and basic null cleanup.
    """
    df = df.drop_duplicates()
    df = df.reset_index(drop=True)
    return df

"""3. Feature & Target Split -"""

def split_features_target(df: pd.DataFrame):
    """
    Separate independent and dependent variables.
    """
    X = df.drop("PlacementStatus", axis=1)
    y = df["PlacementStatus"]
    return X, y

"""4. Build Preprocessing Pipeline -"""

def build_preprocessor(X: pd.DataFrame):
    """
    Build ColumnTransformer pipeline for numerical and categorical features.
    """

    numerical_features = [
        "Age",
        "CGPA",
        "Internships",
        "Projects",
        "Workshops/Certifications",
        "AptitudeTestScore",
        "SoftSkillsRating"
    ]

    categorical_features = [
        "Gender",
        "ExtracurricularActivities"
    ]

    numerical_pipeline = Pipeline(steps=[
        ("imputer", SimpleImputer(strategy="median")),
        ("scaler", StandardScaler())
    ])

    categorical_pipeline = Pipeline(steps=[
        ("imputer", SimpleImputer(strategy="most_frequent")),
        ("encoder", OneHotEncoder(handle_unknown="ignore"))
    ])

    preprocessor = ColumnTransformer(transformers=[
        ("num", numerical_pipeline, numerical_features),
        ("cat", categorical_pipeline, categorical_features)
    ])

    return preprocessor

"""5. Fit & Transform -"""

def preprocess_data(X, preprocessor, save_path="../src/preprocessor.pkl"):
    """
    Fit preprocessor and transform features.
    Save fitted pipeline for reuse.
    """

    X_processed = preprocessor.fit_transform(X)

    joblib.dump(preprocessor, save_path)

    return X_processed

"""6. Full Pipeline Runner"""

from pathlib import Path


def run_preprocessing_pipeline():
    """
    Complete preprocessing workflow with robust path handling.
    """

    # Get project root dynamically
    project_root = Path(__file__).resolve().parent.parent
    data_path = project_root / "data" / "employability_prediction_data.csv"

    df = load_data(data_path)
    df = clean_data(df)

    X, y = split_features_target(df)

    preprocessor = build_preprocessor(X)
    X_processed = preprocess_data(X, preprocessor)

    return X_processed, y