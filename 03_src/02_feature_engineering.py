import pandas as pd
import numpy as np

"""1. Academic Strength Score -"""

def create_academic_score(df: pd.DataFrame) -> pd.DataFrame:
    """
    Combine CGPA and Aptitude score to reflect academic competence.
    """

    df["AcademicScore"] = (
        df["CGPA"] * 0.6 +
        df["AptitudeTestScore"] * 0.4
    )

    return df

"""2. Practical Exposure Score -"""

def create_practical_exposure_score(df: pd.DataFrame) -> pd.DataFrame:
    """
    Aggregate internships, projects, and certifications.
    """

    df["PracticalExposureScore"] = (
        df["Internships"] +
        df["Projects"] +
        df["Workshops/Certifications"]
    )

    return df

"""3. Overall Employability Index -"""

def create_employability_index(df: pd.DataFrame) -> pd.DataFrame:
    """
    Blend academic, practical and soft skills.
    """

    df["EmployabilityIndex"] = (
        df["AcademicScore"] * 0.4 +
        df["PracticalExposureScore"] * 0.4 +
        df["SoftSkillsRating"] * 0.2
    )

    return df

"""4. Feature Interaction -"""

def create_interaction_features(df: pd.DataFrame) -> pd.DataFrame:
    """
    Capture interaction between soft skills and extracurricular activities.
    """

    df["SoftSkill_ExtraInteraction"] = (
        df["SoftSkillsRating"] *
        df["ExtracurricularActivities"]
    )

    return df

