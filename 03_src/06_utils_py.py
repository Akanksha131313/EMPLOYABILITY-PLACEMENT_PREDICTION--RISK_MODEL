import logging
import sys
import numpy as np
import random
from pathlib import Path

"""1. Setup Logger -"""

def setup_logger(name: str = "employability_model") -> logging.Logger:
    """
    Configure and return a reusable logger.
    """

    logger = logging.getLogger(name)
    logger.setLevel(logging.INFO)

    if not logger.handlers:
        handler = logging.StreamHandler(sys.stdout)
        formatter = logging.Formatter(
            "%(asctime)s | %(levelname)s | %(name)s | %(message)s"
        )
        handler.setFormatter(formatter)
        logger.addHandler(handler)

    return logger

"""2. Set Random Seed -"""

def set_random_seed(seed: int = 42):
    """
    Ensure reproducibility across experiments.
    """

    np.random.seed(seed)
    random.seed(seed)

"""3. Validate Input Features -"""

def validate_input_columns(input_df, expected_columns):
    """
    Ensure inference input contains required columns.
    """

    missing_cols = set(expected_columns) - set(input_df.columns)

    if missing_cols:
        raise ValueError(
            f"Missing required input columns: {missing_cols}"
        )

    return True

"""4. Ensure Directory Exists -"""

def ensure_directory(path: Path):
    """
    Create directory if it does not exist.
    """

    path.mkdir(parents=True, exist_ok=True)

"""5. Get Project Root -"""

def get_project_root():
    """
    Returns project root safely for both script and notebook environments.
    """

    try:
        return Path(__file__).resolve().parent.parent
    except NameError:
        return Path.cwd()