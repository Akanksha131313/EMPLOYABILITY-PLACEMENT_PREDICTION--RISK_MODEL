import pandas as pd
import joblib
from pathlib import Path

"""1. Load Model -"""

def load_model(model_path: Path):
    return joblib.load(model_path)

"""2. Prepare Input Data -"""

def prepare_input(data: dict) -> pd.DataFrame:
    """
    Convert user input dictionary into DataFrame
    matching training feature format.
    """

    input_df = pd.DataFrame([data])

    return input_df

"""3. Predict -"""

def make_prediction(model, input_df: pd.DataFrame):

    prediction = model.predict(input_df)[0]

    if hasattr(model, "predict_proba"):
        probability = model.predict_proba(input_df)[0][1]
    else:
        probability = None

    return prediction, probability

"""4. Full Prediction Pipeline -"""

def run_prediction(sample_input: dict):

    from pathlib import Path

    project_root = Path.cwd()

    model_path = project_root / "models" / "best_model.pkl"

    if not model_path.exists():
        raise FileNotFoundError(
            "Model not found. Please run train_model.py first."
        )

    model = load_model(model_path)

    input_df = prepare_input(sample_input)

    prediction, probability = make_prediction(model, input_df)

    print("\nPrediction Result")
    print("-" * 30)
    print("Placement Status:", prediction)